"""Clone one private quality-benchmark input set into three byte-identical runs.

Generate the source set ON YOUR OWN MACHINE with make_set.py first. This script
never downloads photos, uploads anything, opens a customer image, or copies the
results to Git. Keep SEED and ROOT outside the repository and off shared disks.

    python scripts/bench/clone_inputs.py /private/bench/seed /private/bench/trial

It preserves completed renders/scores on a resumed run. If a source photo,
reference truth or manifest in an existing run differs, it FAILS CLOSED rather
than accidentally comparing different identities or changing private inputs.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
LOOK = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
ID = re.compile(r"^[A-Za-z0-9_-]+$")
RUNS = ("baseline", "repeat", "candidate")


def digest(file: Path) -> str:
    h = hashlib.sha256()
    with file.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def outside_repo(path: Path) -> Path:
    resolved = path.resolve()
    if resolved == REPO or resolved.is_relative_to(REPO):
        raise ValueError("Private benchmark paths MUST be outside the Git checkout")
    return resolved


def protected_file(src: Path, dest: Path) -> None:
    if src.is_symlink() or not src.is_file():
        raise ValueError("Source benchmark input missing or symlinked")
    if dest.is_symlink():
        raise ValueError("Destination benchmark input is a symlink")
    dest.parent.mkdir(parents=True, exist_ok=True)
    if dest.exists():
        if not dest.is_file() or digest(dest) != digest(src):
            raise ValueError("Existing benchmark input bytes differ; refusing to overwrite")
    else:
        shutil.copy2(src, dest)
    if digest(dest) != digest(src):
        raise ValueError("Benchmark input verification failed after copy")


def copy_triplet(seed: Path, root: Path) -> dict:
    seed = outside_repo(seed)
    root = outside_repo(root)
    if seed == root or root.is_relative_to(seed) or seed.is_relative_to(root):
        raise ValueError("Seed and output root must not contain one another")
    if not seed.is_dir():
        raise ValueError("No private benchmark seed directory")
    mf = seed / "manifest.json"
    if mf.is_symlink() or not mf.is_file():
        raise ValueError("Missing private benchmark manifest")
    manifest = json.loads(mf.read_text())
    looks = manifest.get("looks")
    engines = manifest.get("engines")
    photos = manifest.get("photos")
    if manifest.get("set") not in ("looks", "full"):
        raise ValueError("Release comparison needs the full 40+-look set")
    if not isinstance(looks, list) or len(looks) < 40 or len(set(looks)) != len(looks):
        raise ValueError("Release comparison needs at least 40 distinct looks")
    if any(not isinstance(x, str) or not LOOK.fullmatch(x) for x in looks):
        raise ValueError("Invalid look ID")
    if engines != ["v1"]:
        raise ValueError("Experimental layer overrides require --engines v1")
    if not isinstance(photos, list) or not photos:
        raise ValueError("Release comparison has no photos")
    paths = [Path("manifest.json")]
    seen = set()
    catalog = []
    for p in photos:
        if not isinstance(p, dict) or not isinstance(p.get("id"), str) or not ID.fullmatch(p["id"]):
            raise ValueError("Invalid private photo ID")
        if p["id"] in seen:
            raise ValueError("Duplicate private photo ID")
        seen.add(p["id"])
        expected = Path("photos") / (p["id"] + ".png")
        if p.get("file") != expected.as_posix():
            raise ValueError("Unsafe or inconsistent private photo location")
        paths.append(expected)
        if p.get("source") == "catalog":
            catalog.append(p["id"])
    if not catalog:
        raise ValueError("No public catalog reference photos")
    for look in looks:
        for photo_id in catalog:
            paths.append(Path("truth") / look / (photo_id + ".png"))
    root.mkdir(parents=True, exist_ok=True)
    for name in RUNS:
        target = root / name
        for relative in paths:
            protected_file(seed / relative, target / relative)
    return {"looks": len(looks), "photos": len(photos),
            "reference_images": len(looks) * len(catalog),
            "triplet_runs": len(RUNS), "manifest_sha256": digest(mf)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("seed", type=Path, help="private seed generated by make_set.py")
    parser.add_argument("root", type=Path, help="private root containing baseline/repeat/candidate")
    a = parser.parse_args()
    print("PRIVATE_TRIPLET_READY " + json.dumps(copy_triplet(a.seed, a.root), sort_keys=True))


if __name__ == "__main__":
    main()
